#!/usr/bin/env python3
"""Update Unit 5 sections in repo README using observed files; keep Unit 6 scaffold."""
from pathlib import Path
from collections import Counter
import json,csv,re

repo=Path(__file__).resolve().parent
readme=repo/'README.md'
source=repo/'UNIT5_README_SECTIONS.md'
if not readme.exists() or not source.exists():
    raise SystemExit('Run inside TakeMeter Git repository after installing files.')
with (repo/'labels.csv').open(encoding='utf-8-sig',newline='') as f:
    rows=list(csv.DictReader(f))
valid={'debugging','implementation','conceptual'}
counts=Counter(r['label'] for r in rows if r['label'] in valid)
cold_done=sum(r['label'] in valid and r['note'].strip().lower()=='cold' for r in rows[:20])
unreviewed=sum('review required' in r['note'].lower() for r in rows[20:])
text=source.read_text(encoding='utf-8').strip()

# Replace the partial table with counts and explicit verification status.
a=text.index('**Counts before independent labeling and review:**')
b=text.index('**Potential hard cases for manual adjudication:**')
label_rows='\n'.join(f'| `{label}` | {counts[label]} | {counts[label]/len(rows):.1%} |' for label in ('debugging','implementation','conceptual'))
new=f"""**Observed dataset counts:** {len(rows)} unique public posts. Independently labeled first-20: {cold_done}/20. AI-suggested labels awaiting personal review: {unreviewed}/200.\n\n| Label | Current count | Share |\n|---|---:|---:|\n{label_rows}\n| **Total labeled** | **{sum(counts.values())}** | **{sum(counts.values())/len(rows):.1%}** |\n\n"""
text=text[:a]+new+text[b:]

# Replace placeholder and status only from actual status/results.
rfile=repo/'results.json'; split=repo/'test_split.csv'
if rfile.exists() and split.exists():
    r=json.loads(rfile.read_text(encoding='utf-8'))
    status='**Actual training:** completed locally. Held-out accuracy: '+str(r.get('accuracy','see results.json'))+', macro F1: '+str(r.get('f1_macro','see results.json'))+'. The exported metrics are in `results.json`; the held-out data is in `test_split.csv`.'
    text=text.replace('**Device:** pending notebook output.','**Device:** '+str(r.get('device','see results.json'))+'.')
else:
    status='**Actual training:** NOT YET RUN. No measured results files have been produced.'
text=re.sub(r'\*\*Status:\*\*[^\n]*',status,text)
if cold_done==20:
    text=text.replace('The first 20 posts are reserved for independent cold labeling.', 'The first 20 posts were independently cold labeled in the local project.')
if rfile.exists() and split.exists():
    text=text.replace('The trained result is not yet recorded here; `results.json` and `test_split.csv` must be generated by running notebook sections 1–5.', 'The local training result was generated by the original Unit 5 notebook; actual metrics are recorded in `results.json` and the held-out data is saved in `test_split.csv`.')
if unreviewed:
    text += f'\n\n**Disclosure at write-up:** {unreviewed} AI-suggested rows are still unreviewed and must not be reported as personally checked.\n'

body=readme.read_text(encoding='utf-8')
start='## What This Does';end='## Baseline vs. Trained'
if start not in body or end not in body:
    raise SystemExit('Expected original README headings missing. Please preserve original scaffold.')
a=body.index(start);b=body.index(end,a)
body=body[:a]+text+'\n\n---\n\n'+body[b:]
readme.write_text(body,encoding='utf-8')
print('Updated README Unit 5 sections. Unit 6 remains unchanged.')
print(f'Cold: {cold_done}/20; unreviewed AI suggestions: {unreviewed}; results: {rfile.exists() and split.exists()}')
